-- A) ¿EXISTEN las tablas que usa el backend? (documents y expenses)
select table_name
  from information_schema.tables
 where table_schema = 'public'
   and table_name in ('documents', 'expenses')
 order by table_name;
-- Si solo aparece 'documents' o no aparece 'expenses', el SQL del paso 1 no se ejecuto
-- en ESTE proyecto: ejecuta de nuevo server/supabase-expenses.sql aqui.

-- B) ¿QUE ROL USA EL BACKEND? Esta es la clave del problema.
--    El backend se conecta con SUPABASE_SECRET_KEY. Si en Render esa variable contiene
--    la clave 'anon' o la 'publishable' en vez de la 'service_role' / 'sb_secret_...',
--    Supabase la trata como usuario sin privilegios y devuelve 42501 aunque los grants
--    esten aplicados. Esta consulta no lo puede ver (depende de la clave), asi que
--    compruebalo tu en el panel de Render (ver nota de abajo).
--
-- C) ¿TIENEN PERMISOS los roles que usa Supabase por defecto?
select
  grantee,
  table_name,
  string_agg(privilege_type, ', ' order by privilege_type) as permisos
  from information_schema.role_table_grants
 where table_schema = 'public'
   and table_name in ('documents', 'expenses')
   and grantee in ('service_role', 'anon', 'authenticated', 'postgres')
 group by grantee, table_name
 order by table_name, grantee;
-- Referencia de lo correcto:
--   documents  -> service_role: INSERT, SELECT, UPDATE, DELETE (+ postgres)
--   expenses   -> service_role: INSERT, SELECT, UPDATE, DELETE (+ postgres)
-- Si 'service_role' NO aparece, los grants no se aplicaron a esta tabla.
-- Si 'service_role' aparece y aun asi falla -> la clave de Render no es la de service_role.

-- D) ¿ESTAN ACTIVAS LAS POLITICAS RLS? (no es el problema actual, pero conviene verlo)
select tablename, rowsecurity, forcerowsecurity
  from pg_tables
 where schemaname = 'public'
   and tablename in ('documents', 'expenses')
 order by tablename;
-- rowsecurity = true es lo normal: service_role las ignora, asi que no es la causa.

-- E) COMPROBACION FINAL de permisos, como los ve el backend:
select has_table_privilege('service_role', 'public.documents', 'INSERT') as doc_insert,
       has_table_privilege('service_role', 'public.documents', 'SELECT') as doc_select,
       has_table_privilege('service_role', 'public.expenses',  'INSERT') as exp_insert,
       has_table_privilege('service_role', 'public.expenses',  'SELECT') as exp_select;
-- Las 4 deben ser true. Si son false, vuelve a ejecutar el bloque de permisos de abajo.
