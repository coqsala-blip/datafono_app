begin;

-- 1) La tabla de gastos (idempotente).
create table if not exists public.expenses (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  local_id text not null,
  based_on text not null default 'client',
  description text not null default '',
  amount numeric not null default 0,
  date date,
  category text not null default 'Otros',
  synced_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  unique (user_id, local_id, based_on)
);

-- 2) Columnas que necesita el backend en documents.
alter table public.documents
  add column if not exists user_id uuid references auth.users (id) on delete set null;
alter table public.documents
  add column if not exists updated_at timestamptz not null default now();

create index if not exists documents_user_id_created_at_idx
  on public.documents (user_id, created_at desc);

-- 3) RLS + politica de gastos (se elimina antes para poder repetir el script).
alter table public.expenses enable row level security;
drop policy if exists "Users manage own expenses" on public.expenses;
create policy "Users manage own expenses"
  on public.expenses
  for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

-- 4) PERMISOS: esta es la parte que resuelve el error. 'service_role' es el rol del
--    backend (si en Render usas la clave secreta nueva, el rol se llama 'service_role'
--    igualmente, asi que el grant sigue siendo valido).
grant usage on schema public to service_role;
grant all on all tables in schema public to service_role;
grant all on all sequences in schema public to service_role;
-- Grants explicitos por tabla, por si 'all on all tables' se quedo corto.
grant select, insert, update, delete on public.documents to service_role;
grant select, insert, update, delete on public.expenses  to service_role;
grant usage, select on all sequences in schema public to service_role;

commit;

