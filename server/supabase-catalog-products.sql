-- Catálogo de productos del comercio (compartido entre móviles y usuarios de la misma empresa).
-- Ejecutar en Supabase: Dashboard -> SQL Editor -> pegar y Run.
create table if not exists public.catalog_products (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  local_id text not null,
  name text not null default '',
  price numeric not null default 0,
  photo_data text,
  created_at timestamptz not null default now(),
  synced_at timestamptz not null default now(),
  unique (user_id, local_id)
);

alter table public.catalog_products enable row level security;

drop policy if exists "Users manage own catalog products" on public.catalog_products;

create policy "Users manage own catalog products"
  on public.catalog_products
  for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

grant usage on schema public to service_role;
grant select, insert, update, delete on public.catalog_products to service_role;
grant usage, select on all sequences in schema public to service_role;
