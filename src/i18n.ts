export const APP_LOCALE_STORAGE_KEY = '@tpv_app_locale_v1';

export const isAppLocale = (value: unknown): value is AppLocale =>
  typeof value === 'string' &&
  (['es', 'en', 'fr', 'de', 'it', 'pt', 'nl', 'pl'] as string[]).includes(value);

// Mapea región del dispositivo (ES, FR, DE...) al idioma de la app.
export const localeForRegion = (regionCode: string | null | undefined): AppLocale | null => {
  const region = String(regionCode || '').toUpperCase();
  if (!region) return null;
  if (['ES', 'MX', 'AR', 'CO', 'CL', 'PE'].includes(region)) return 'es';
  if (['FR', 'BE', 'LU', 'CH'].includes(region)) return 'fr';
  if (['DE', 'AT'].includes(region)) return 'de';
  if (['IT', 'SM'].includes(region)) return 'it';
  if (['PT'].includes(region)) return 'pt';
  if (['NL'].includes(region)) return 'nl';
  if (['PL'].includes(region)) return 'pl';
  if (['IE', 'MT', 'GB', 'US'].includes(region)) return 'en';
  return null;
};

export const localeForLanguageTag = (tag: string | null | undefined): AppLocale | null => {
  const code = String(tag || '').toLowerCase().split(/[-_]/)[0];
  return isAppLocale(code) ? code : null;
};

const CURRENCY_LOCALE: Record<AppLocale, string> = {
  es: 'es-ES',
  en: 'en-IE',
  fr: 'fr-FR',
  de: 'de-DE',
  it: 'it-IT',
  pt: 'pt-PT',
  nl: 'nl-NL',
  pl: 'pl-PL',
};

export const formatCurrencyForLocale = (locale: AppLocale, amount: number): string => {
  try {
    return new Intl.NumberFormat(CURRENCY_LOCALE[locale] || 'es-ES', {
      style: 'currency',
      currency: 'EUR',
    }).format(amount);
  } catch {
    return new Intl.NumberFormat('es-ES', { style: 'currency', currency: 'EUR' }).format(amount);
  }
};

